export function getEmirate(slug) {
  return UAE_EMIRATES.find((item) => item.slug === slug) || null;
}

export function getArea(emirateSlug, areaSlug) {
  const emirate = getEmirate(emirateSlug);
  if (!emirate) return null;
  return emirate.areas.find((item) => item.slug === areaSlug) || null;
}

export function getServiceCategory(slug) {
  return SERVICE_CATEGORIES.find((item) => item.slug === slug) || null;
}

export function getAllAreaPaths() {
  return UAE_EMIRATES.flatMap((emirate) =>
    emirate.areas.map((area) => ({ emirate: emirate.slug, area: area.slug }))
  );
}

export function getAllAreaServicePaths() {
  return UAE_EMIRATES.flatMap((emirate) =>
    emirate.areas.flatMap((area) =>
      SERVICE_CATEGORIES.map((service) => ({
        emirate: emirate.slug,
        area: area.slug,
        service: service.slug
      }))
    )
  );
}

